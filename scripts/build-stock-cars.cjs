// Builds renderer/stock-cars.js, the nine stock cars of the Showroom, from the SlotForge Decal
// Creator livery templates:
//   SlotForge-Stock-Cars.sfpaint                → the left, right and top views
//   photo-angled/SlotForge-Angled-Cars.sfpaint  → the angled view (the angled-only set)
// Usage: node scripts/build-stock-cars.cjs [path to livery-templates]
// The cars are read only; nothing in the source folder is changed.
const fs = require('node:fs'),
  path = require('node:path');
const root = path.resolve(__dirname, '..'),
  source = path.resolve(
    process.argv[2] || path.join(root, '..', '..', 'ChatGPT', 'SlotForge Decal Creator', 'livery-templates')
  ),
  out = path.join(root, 'renderer', 'stock-cars.js');
// Showroom order, the short key and the kind each car is filed under.
const CARS = [
  ['GT3', 'gt3', 'gt'],
  ['Classic GT', 'classic-gt', 'gt'],
  ['Touring Car', 'touring', 'gt'],
  ['Group C Prototype', 'group-c', 'prototype'],
  ['Modern Prototype', 'modern-prototype', 'prototype'],
  ['Classic Formula', 'classic-formula', 'formula'],
  ['Modern Formula', 'modern-formula', 'formula'],
  ['Rally Hatchback', 'rally', 'rally'],
  ['Stock Car', 'stock-car', 'rally']
];
const read = file => {
  const pkg = JSON.parse(fs.readFileSync(path.join(source, file), 'utf8'));
  if (pkg.format !== 'slotforge-paintshop' || pkg.kind !== 'library')
    throw Error(`${file} is not a Livery library package.`);
  return pkg.data.templates;
};
const sides = read('SlotForge-Stock-Cars.sfpaint'),
  angled = read(path.join('photo-angled', 'SlotForge-Angled-Cars.sfpaint'));
const cars = CARS.map(([name, key, kind]) => {
  const a = sides.find(t => t.name === name),
    b = angled.find(t => t.name === name);
  if (!a || !b) throw Error(`${name} is missing from the packages.`);
  for (const view of ['left', 'right', 'top']) if (!a.views[view]) throw Error(`${name} has no ${view} view.`);
  if (!b.views.angled) throw Error(`${name} has no angled view.`);
  return {
    key,
    kind,
    template: {
      name,
      scale: '',
      creator: 'SlotForge',
      description: 'A SlotForge stock car from the Showroom.',
      views: { left: a.views.left, right: a.views.right, top: a.views.top, angled: b.views.angled }
    }
  };
});
const text = `// The nine Showroom stock cars. Generated by scripts/build-stock-cars.cjs; do not edit.
// Loaded only when the Showroom opens. Each car is checked like an imported car before use.
window.STOCK_CARS = ${JSON.stringify(cars)};
`;
fs.writeFileSync(out, text);
console.log(`Wrote ${path.relative(root, out)}: ${cars.length} cars, ${(text.length / 1048576).toFixed(1)} MB.`);
