const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('desktop', {
  load: () => ipcRenderer.invoke('library:load'),
  version: () => ipcRenderer.invoke('app:version'),
  ready: () => ipcRenderer.send('app:ready'),
  save: data => ipcRenderer.invoke('library:save', data),
  restore: data => ipcRenderer.invoke('library:restore', data),
  libraryItem: key => ipcRenderer.invoke('library:item', key),
  libraryPreview: key => ipcRenderer.invoke('library:preview', key),
  libraryThumbnail: data => ipcRenderer.invoke('library:thumbnail', data),
  libraryMissingMedia: hashes => ipcRenderer.invoke('library:missing-media', hashes),
  librarySnapshot: () => ipcRenderer.invoke('library:snapshot'),
  exportPackage: payload => ipcRenderer.invoke('package:save', payload),
  exportDecals: payload => ipcRenderer.invoke('decals:save', payload),
  chooseBackupFolder: () => ipcRenderer.invoke('backup:choose-folder'),
  writeBackup: payload => ipcRenderer.invoke('backup:write', payload),
  listBackups: folder => ipcRenderer.invoke('backup:list', folder),
  readBackup: payload => ipcRenderer.invoke('backup:read', payload),
  revealBackup: payload => ipcRenderer.invoke('backup:reveal', payload),
  knownBackupFolder: () => ipcRenderer.invoke('backup:known-folder'),
  libraryFiles: () => ipcRenderer.invoke('library:files'),
  revealLibrary: () => ipcRenderer.invoke('library:reveal'),
  // Update check (Settings → Updates and the update window); resolves to { ok, value } or { error }.
  updateCheck: (action, payload) => ipcRenderer.invoke('update:action', String(action), payload),
  onUpdateChange: callback => ipcRenderer.on('update:changed', () => callback()),
  exportPNG: payload => ipcRenderer.invoke('png:save', payload),
  exportPDF: payload => ipcRenderer.invoke('pdf:save', payload),
  convertVector: payload => ipcRenderer.invoke('vector:convert', payload),
  onClosing: callback => ipcRenderer.on('app:closing', callback),
  closeReady: () => ipcRenderer.send('app:close-ready')
});
